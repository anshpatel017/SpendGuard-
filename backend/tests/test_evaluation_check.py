"""Every sourced figure in EVALUATION.md must match the file that generated it.

Phase 9's exit criterion is that every number in the evaluation document comes
from a reproducible command. Section 4.0b already says so in prose - this is
what turns that promise into something that can fail.

Same reasoning as the policy/config agreement check: a number stated in two
places drifts, and on this project the drift would be invisible, because nobody
re-derives a table they can already read.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from spendguard.eval.evaluation_check import (
    EvaluationParseError,
    find_disagreements,
)

METRICS = ("precision", "recall", "f1", "pr_auc")


def _results(path: Path, f1: float = 0.949) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / "detection.json").write_text(
        json.dumps(
            {
                "aggregate": [
                    {
                        "anomaly_type": "duplicate",
                        "detector": "d1",
                        "granularity": "case",
                        "precision": {"mean": 1.0, "sd": 0.0},
                        "recall": {"mean": 0.903, "sd": 0.016},
                        "f1": {"mean": f1, "sd": 0.009},
                        "pr_auc": {"mean": 0.903, "sd": 0.016},
                    },
                    {  # a per-row row, which the document does not quote here
                        "anomaly_type": "duplicate",
                        "detector": "d1",
                        "granularity": "row",
                        "precision": {"mean": 0.1, "sd": 0.0},
                        "recall": {"mean": 0.1, "sd": 0.0},
                        "f1": {"mean": 0.1, "sd": 0.0},
                        "pr_auc": {"mean": 0.1, "sd": 0.0},
                    },
                ]
            }
        ),
        encoding="utf-8",
    )


DOCUMENT = """# Evaluation

### 4.0a An older snapshot, deliberately unmarked

| Anomaly | Detector | Precision | Recall | F1 | PR-AUC |
|---|---|---:|---:|---:|---:|
| duplicate | **D1** | 1.000 ± 0.000 | 0.888 ± 0.013 | 0.111 ± 0.007 | 0.888 ± 0.013 |

### 4.0b Results

> **Source:** [`docs/results/detection.md`](results/detection.md), generated by \
`spendguard report detection` at commit `abc1234`.

| Anomaly | Detector | Precision | Recall | F1 | PR-AUC |
|---|---|---:|---:|---:|---:|
| duplicate | **D1** | **1.000 ± 0.000** | **0.903 ± 0.016** | **0.949 ± 0.009** | **0.903 ± 0.016** |

**Some prose afterwards**, with a number like 0.419 in it that is not a table row.
"""


@pytest.fixture
def document(tmp_path: Path) -> Path:
    path = tmp_path / "EVALUATION.md"
    path.write_text(DOCUMENT, encoding="utf-8")
    return path


def test_a_document_whose_figures_match_its_results_passes(document: Path, tmp_path: Path) -> None:
    _results(tmp_path / "results")
    assert find_disagreements(document, tmp_path / "results") == []


def test_a_figure_edited_by_hand_is_caught(document: Path, tmp_path: Path) -> None:
    """The failure this exists for: someone updates the prose and not the run."""
    _results(tmp_path / "results", f1=0.912)
    (problem,) = find_disagreements(document, tmp_path / "results")
    assert problem.metric == "f1"
    assert problem.quoted == 0.949 and problem.generated == 0.912
    assert "0.949" in str(problem) and "0.912" in str(problem)


def test_rounding_in_the_last_place_is_not_a_disagreement(document: Path, tmp_path: Path) -> None:
    """The document rounds to three decimals; that must not read as drift."""
    _results(tmp_path / "results", f1=0.94912)
    assert find_disagreements(document, tmp_path / "results") == []


def test_only_tables_that_claim_a_source_are_checked(document: Path, tmp_path: Path) -> None:
    """4.0a is a Phase 3 snapshot with different numbers and no Source line.

    Checking it would fail forever, or force a historical record to be rewritten
    every time the detectors change - neither of which is what the criterion means.
    """
    _results(tmp_path / "results")
    assert find_disagreements(document, tmp_path / "results") == []  # 0.111 in 4.0a is ignored


def test_a_row_the_results_file_does_not_contain_is_reported(tmp_path: Path) -> None:
    path = tmp_path / "EVALUATION.md"
    path.write_text(DOCUMENT.replace("**D1**", "**D9**"), encoding="utf-8")
    _results(tmp_path / "results")
    (problem,) = find_disagreements(path, tmp_path / "results")
    assert problem.generated is None
    assert "absent from the results file" in str(problem)


def test_citing_a_results_file_that_was_never_generated_is_an_error(
    document: Path, tmp_path: Path
) -> None:
    with pytest.raises(EvaluationParseError, match="does not exist"):
        find_disagreements(document, tmp_path / "nothing")


def test_a_document_with_no_sourced_table_fails_loudly(tmp_path: Path) -> None:
    """A check that silently passes because it found nothing to check is worse than none."""
    path = tmp_path / "EVALUATION.md"
    path.write_text("# Evaluation\n\nNo tables here.\n", encoding="utf-8")
    with pytest.raises(EvaluationParseError, match="no table marked"):
        find_disagreements(path, tmp_path / "results")


def test_the_real_evaluation_document_agrees_with_the_committed_results() -> None:
    """The one that matters: docs/EVALUATION.md against docs/results/, as committed."""
    assert find_disagreements() == []


def test_a_metric_the_document_writes_as_a_dash_does_not_skip_the_whole_row(
    tmp_path: Path,
) -> None:
    """The pooled suite row quotes no PR-AUC, and requiring every cell to parse
    silently skipped that row - and with it the system-level F1, the most quoted
    number in the project."""
    path = tmp_path / "EVALUATION.md"
    path.write_text(
        DOCUMENT.replace(
            "| duplicate | **D1** | **1.000 ± 0.000** | **0.903 ± 0.016** | "
            "**0.949 ± 0.009** | **0.903 ± 0.016** |",
            "| all | **spendguard** | **1.000 ± 0.000** | **0.903 ± 0.016** | "
            "**0.911 ± 0.009** | - |",
        ),
        encoding="utf-8",
    )
    results = tmp_path / "results"
    results.mkdir(parents=True, exist_ok=True)
    (results / "detection.json").write_text(
        json.dumps(
            {
                "aggregate": [
                    {
                        "anomaly_type": "all",
                        "detector": "spendguard",
                        "granularity": "case",
                        "precision": {"mean": 1.0, "sd": 0.0},
                        "recall": {"mean": 0.903, "sd": 0.016},
                        "f1": {"mean": 0.689, "sd": 0.009},
                        "pr_auc": None,  # pooling a ranking across four scorers is meaningless
                    }
                ]
            }
        ),
        encoding="utf-8",
    )
    (problem,) = find_disagreements(path, results)
    assert problem.metric == "f1" and problem.quoted == 0.911 and problem.generated == 0.689
