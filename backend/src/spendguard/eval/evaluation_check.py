"""Check that the figures quoted in ``docs/EVALUATION.md`` match what produced them.

Phase 9's exit criterion is that every number in the evaluation document comes
from a reproducible command. Section 4.0b already says where its table came from
and that it must not be edited by hand - but saying so is an honour system. The
numbers live in the prose *and* in ``docs/results/detection.json``, and two
copies of a number drift. On this project that drift would be invisible: nobody
re-derives a table they can already read.

So this parses the figures back out of the prose and compares them to the
generated results. It is the same move as ``policy_check.py``, which exists
because ₹2,50,000 appears in both the policy and the config, and for the same
reason: a number stated twice needs something that notices when the two
disagree.

**What is checked.** Any Markdown table that follows a "Source:" line naming a
generated file under ``docs/results/``. That marker is what makes a table a
claim about a command's output rather than a historical note - section 4.0a, a
Phase 3 snapshot, carries no marker and is deliberately left alone.

``spendguard check-evaluation`` runs it; a test asserts it passes.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from spendguard.config import settings

# "> **Source:** [`docs/results/detection.md`](results/detection.md), generated by ..."
_SOURCE = re.compile(r"^>\s*\*\*Source:\*\*.*?results/(?P<file>[\w.-]+\.md)", re.MULTILINE)
# A table row: "| duplicate | **D1** | **1.000 ± 0.000** | ... |"
_ROW = re.compile(r"^\|(?P<cells>.+)\|\s*$")
# "1.000 ± 0.000" or "**0.949 ± 0.009**" or a bare "0.419"
_FIGURE = re.compile(r"^\*{0,2}(?P<mean>[\d.]+)(?:\s*±\s*(?P<sd>[\d.]+))?\*{0,2}$")

# How close a quoted figure must be to the generated one. The document rounds to
# three decimals, so anything beyond half a unit in the last place is a real
# disagreement rather than a rounding difference.
TOLERANCE = 0.0005

METRICS = ("precision", "recall", "f1", "pr_auc")


class EvaluationParseError(RuntimeError):
    """The evaluation document could not be parsed as expected."""


@dataclass(frozen=True)
class Disagreement:
    """One figure in the prose that does not match the file it claims to come from."""

    table: str
    row: str
    metric: str
    quoted: float
    generated: float | None

    def __str__(self) -> str:
        found = (
            "absent from the results file" if self.generated is None else f"{self.generated:.3f}"
        )
        return (
            f"{self.table}: {self.row} {self.metric} - EVALUATION.md says {self.quoted:.3f}, "
            f"{found}"
        )


def _cells(line: str) -> list[str]:
    found = _ROW.match(line.strip())
    if not found:
        return []
    return [c.strip() for c in found.group("cells").split("|")]


def _figure(cell: str) -> tuple[float, float | None] | None:
    found = _FIGURE.match(cell.strip())
    if not found:
        return None
    sd = found.group("sd")
    return float(found.group("mean")), (float(sd) if sd is not None else None)


def _sourced_tables(text: str) -> list[tuple[str, str, list[list[str]]]]:
    """Every (results file, heading, rows) whose table follows a Source marker."""
    tables = []
    lines = text.splitlines()
    heading = "(top)"
    pending: str | None = None
    rows: list[list[str]] = []
    for line in lines:
        if line.startswith("#"):
            if pending and rows:
                tables.append((pending, heading, rows))
            heading, pending, rows = line.lstrip("# ").strip(), None, []
            continue
        marker = _SOURCE.match(line)
        if marker:
            pending, rows = marker.group("file"), []
            continue
        if pending is None:
            continue
        cells = _cells(line)
        if cells and not all(set(c) <= set("-: ") for c in cells):
            rows.append(cells)
    if pending and rows:
        tables.append((pending, heading, rows))
    return tables


def _generated_metrics(path: Path) -> dict[tuple[str, str], dict[str, float]]:
    """Per-case metrics from a generated detection report, keyed by (anomaly, detector)."""
    payload = json.loads(path.read_text(encoding="utf-8"))
    found: dict[tuple[str, str], dict[str, float]] = {}
    for row in payload.get("aggregate", []):
        if row.get("granularity") != "case":
            continue
        key = (str(row["anomaly_type"]), str(row["detector"]))
        found[key] = {
            metric: value["mean"]
            for metric in METRICS
            if isinstance(value := row.get(metric), dict) and "mean" in value
        }
    return found


def find_disagreements(
    evaluation_path: Path | None = None, results_dir: Path | None = None
) -> list[Disagreement]:
    """Every figure in a sourced table that does not match its generated file."""
    evaluation_path = evaluation_path or settings.project_root / "docs" / "EVALUATION.md"
    results_dir = results_dir or settings.results_dir
    if not evaluation_path.exists():
        raise EvaluationParseError(f"No evaluation document at {evaluation_path}")

    text = evaluation_path.read_text(encoding="utf-8")
    tables = _sourced_tables(text)
    if not tables:
        raise EvaluationParseError(
            f"{evaluation_path.name} has no table marked with a `> **Source:**` line. Either the "
            "marker changed or the generated tables were removed; this check would then pass "
            "while checking nothing."
        )

    problems: list[Disagreement] = []
    for filename, heading, rows in tables:
        results = results_dir / filename.replace(".md", ".json")
        if not results.exists():
            raise EvaluationParseError(
                f"{heading} cites {filename}, but {results} does not exist. Run the command that "
                "generates it before reporting its numbers."
            )
        if "detection" not in filename:
            continue  # only the detection table has a machine-checkable shape so far
        generated = _generated_metrics(results)
        for cells in rows:
            problems += _check_row(heading, cells, generated)
    return problems


def _check_row(
    heading: str, cells: list[str], generated: dict[tuple[str, str], dict[str, float]]
) -> list[Disagreement]:
    if len(cells) < 2 + len(METRICS):
        return []
    anomaly = cells[0].strip("* ").lower()
    detector = cells[1].strip("* ").lower()
    figures = [_figure(c) for c in cells[2 : 2 + len(METRICS)]]
    # A cell may legitimately be "-": the pooled suite row quotes no PR-AUC,
    # because one ranking across four independent scorers is not meaningful.
    # Requiring *every* cell to parse silently skipped that whole row - and with
    # it the system-level F1, the most quoted number in the project. A row counts
    # as a metrics row if any cell is a figure; the "-" cells are skipped below.
    if not any(f is not None for f in figures):
        return []  # a header or a prose row, not a metrics row

    known = generated.get((anomaly, detector))
    if known is None:
        return [
            Disagreement(heading, f"{anomaly}/{detector}", metric, figure[0], None)
            for metric, figure in zip(METRICS, figures, strict=True)
            if figure is not None
        ][:1]  # one complaint per row is enough to find it

    problems = []
    for metric, figure in zip(METRICS, figures, strict=True):
        if figure is None:
            continue  # "-": the document does not quote this metric for this row
        quoted = figure[0]
        value = known.get(metric)
        if value is None or abs(value - quoted) > TOLERANCE:
            problems.append(Disagreement(heading, f"{anomaly}/{detector}", metric, quoted, value))
    return problems
